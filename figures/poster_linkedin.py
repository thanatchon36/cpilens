"""A one-image poster for social media: the question, three headline numbers and the
basis-point chart. Every number comes from ``paper/numbers.tex`` and ``results/`` (nothing is
typed here), in the figure house style. Portrait 4:5, 2,400 x 3,000 px.

Usage: ``python figures/poster_linkedin.py`` -> ``docs/assets/poster_linkedin.png``.
"""

from __future__ import annotations

import re
import textwrap

import matplotlib.pyplot as plt
import polars as pl
from matplotlib.lines import Line2D
from matplotlib.patches import FancyBboxPatch

from cpilens.evaluate.run import CASCADE_CHEAP, LLMS
from cpilens.paths import ROOT
from cpilens.viz import names, select, style

OUT = ROOT / "docs" / "assets" / "poster_linkedin.png"
PAPER_URL = "github.com/thanatchon36/cpilens"
DOI = "10.5281/zenodo.23686886"
TILE_BG = "#f4f4f1"
METHODS = [*CASCADE_CHEAP, *LLMS, f"cascade__{CASCADE_CHEAP[0]}__{LLMS[1]}"]


def macros() -> dict[str, str]:
    text = (ROOT / "paper" / "numbers.tex").read_text(encoding="utf-8")
    return {
        m.group(1): m.group(2).replace("{,}", ",").replace("\\%", "%")
        for m in re.finditer(r"\\newcommand\{\\(\w+)\}\{(.*)\}$", text, re.M)
    }


def tile(fig: plt.Figure, x: float, y: float, w: float, h: float, value: str, label: str) -> None:
    fig.patches.append(
        FancyBboxPatch(
            (x, y),
            w,
            h,
            boxstyle="round,pad=0,rounding_size=0.01",
            transform=fig.transFigure,
            facecolor=TILE_BG,
            edgecolor="none",
        )
    )
    fig.text(x + 0.025, y + h - 0.06, value, fontsize=46, fontweight="semibold", va="top")
    fig.text(
        x + 0.025,
        y + h - 0.14,
        textwrap.fill(label, 34),
        fontsize=13.5,
        color=style.MUTED,
        va="top",
        linespacing=1.3,
    )


def main() -> None:
    style.setup()
    v = macros()
    results = ROOT / "results"
    fig = plt.figure(figsize=(12, 15), dpi=100)
    left, right = 0.07, 0.93

    fig.text(
        left,
        0.955,
        "OPEN RESEARCH  ·  PUBLIC DATA ONLY  ·  THAI CPI",
        fontsize=14,
        color=style.FAMILY["embedding"],
        va="top",
    )
    fig.text(
        left,
        0.925,
        "How much does product classification\ncost in basis points?",
        fontsize=46,
        fontweight="bold",
        va="top",
        linespacing=1.1,
    )
    fig.text(
        left,
        0.815,
        textwrap.fill(
            "Web and scanner prices enter a consumer price index only after each product is "
            "assigned to an item of the basket. For Thai product text, this study measures what "
            "that step costs in measured inflation, with public data only.",
            92,
        ),
        fontsize=17,
        color=style.MUTED,
        va="top",
        linespacing=1.35,
    )

    tiles = [
        (
            f"{v['AccWOpus']}%",
            f"of the CPI weight classified correctly by {v['NameOpus']}, on "
            f"{v['NRefSpecs']} held-out official price-collection specifications",
        ),
        (
            f"{v['BpYoyRmseHeadlineOpus']} bp",
            "its error in headline year-on-year inflation "
            f"(RMSE); at most {v['BpYoyRmseHeadlineOpusClusterHi']} bp when errors are allowed "
            "to cluster",
        ),
        (
            f"USD {v['LLMSpendUSD']}",
            "total LLM spend for the whole study; every number generated by code from open data",
        ),
    ]
    gap, w, h, y0 = 0.025, (right - left - 2 * 0.025) / 3, 0.21, 0.535
    for i, (value, label) in enumerate(tiles):
        tile(fig, left + i * (w + gap), y0, w, h, value, label)

    # the chart: headline year-on-year error of the main methods, as in the paper's Figure 10
    d = pl.read_csv(results / "rq3_errors.csv").filter(
        (pl.col("weights") == "equal")
        & (pl.col("universe") == "cpi")
        & (pl.col("kind") == "yoy")
        & (pl.col("aggregate") == "headline")
    )
    full = d.filter(pl.col("variant") == "full")
    cl = d.filter(pl.col("variant") == "cluster")
    ms = METHODS[::-1]
    ax = fig.add_axes((0.30, 0.225, 0.62, 0.235))
    for y, m in enumerate(ms):
        r = full.filter(pl.col("method") == m).row(0, named=True)
        rc = cl.filter(pl.col("method") == m).row(0, named=True)
        c = style.FAMILY[select.family(m)]
        ax.plot([rc["rmse_bp_lo"], rc["rmse_bp_hi"]], [y, y], color=c, lw=1.6)
        ax.plot(
            [r["rmse_bp_lo"], r["rmse_bp_hi"]],
            [y, y],
            color=c,
            lw=9,
            alpha=0.35,
            solid_capstyle="butt",
        )
        ax.plot(r["rmse_bp"], y, "o", color=c, ms=11, mec="white", mew=1.5, clip_on=False, zorder=3)
    extremes = full.filter(pl.col("method").is_in(ms)).sort("rmse_bp")
    for row in (extremes.row(0, named=True), extremes.row(-1, named=True)):
        ax.annotate(
            f"{row['rmse_bp']:.1f}",
            (row["rmse_bp"], ms.index(row["method"])),
            xytext=(0, 12),
            textcoords="offset points",
            ha="center",
            fontsize=14,
        )
    ax.set_yticks(range(len(ms)), [names.method(m) for m in ms], fontsize=15)
    ax.tick_params(axis="x", labelsize=14)
    ax.set_xlim(left=0)
    ax.set_ylim(-0.6, len(ms) - 0.4)
    ax.grid(axis="x")
    ax.grid(axis="y", visible=False)
    ax.set_xlabel("RMSE of the year-on-year headline inflation error (basis points)", fontsize=15)
    fams = list(dict.fromkeys(select.family(m) for m in METHODS))
    fig.legend(
        [
            Line2D([], [], color=style.FAMILY[f], lw=9, alpha=0.5, marker="o", ms=11, mew=0)
            for f in fams
        ],
        [names.FAMILY[f] for f in fams],
        loc="upper left",
        bbox_to_anchor=(left - 0.008, 0.170),
        ncols=2,
        fontsize=14,
        frameon=False,
        handlelength=2.2,
        columnspacing=2.0,
    )
    fig.text(
        left,
        0.505,
        "The same errors, in the unit a central bank uses: basis points of headline inflation",
        fontsize=20,
        fontweight="semibold",
        va="top",
    )
    fig.text(
        left,
        0.108,
        textwrap.fill(
            "Dot: point estimate.  Thick line: 95% interval, specifications independent.  "
            "Thin line: 95% interval, errors clustered by sub-item.  Products in proportion to "
            "CPI weights.",
            118,
        ),
        fontsize=12.5,
        color=style.MUTED,
        va="top",
        linespacing=1.35,
    )
    fig.text(
        left,
        0.068,
        textwrap.fill(
            f"Thanatchon Chongmankhong  ·  Paper, code and data: {PAPER_URL}  ·  DOI {DOI}. "
            "Not directly comparable with the BIS Innovation Hub's Project Spectrum (different "
            "data, taxonomy and languages). The views expressed are the author's own and do not "
            "necessarily reflect those of the Bank of Thailand. This work uses only publicly "
            "available data.",
            118,
        ),
        fontsize=12.5,
        color=style.MUTED,
        va="top",
        linespacing=1.35,
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT, dpi=200, facecolor="white")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
